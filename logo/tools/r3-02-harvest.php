<?php

declare(strict_types=1);

/**
 * harvest.php — BUILD-TIME ONLY (never run per-frame).
 *
 * Runs the two logo snippets through the REAL Phpdup\Normalization\Normalizer
 * in strict / default / aggressive modes and captures exactly what the engine
 * returns. The logo never invents tokens: if the Normalizer changes, rerunning
 * this file changes the art. Output is frozen into normalized.php (--write)
 * which DupBanner.php loads once at construction — the repo is NOT touched by
 * playback/verify/frame rendering.
 *
 *   php harvest.php           # print probe table
 *   php harvest.php --write   # also (re)write normalized.php
 *
 * Repo is used read/execute-only (require of vendor/autoload.php).
 */

require '/home/sites/php-dup-finder/vendor/autoload.php';

use PhpParser\Node;
use PhpParser\NodeFinder;
use PhpParser\ParserFactory;
use PhpParser\PrettyPrinter\Standard;
use Phpdup\Extraction\Block;
use Phpdup\Normalization\Normalizer;
use Phpdup\Util\LineRange;

$REPO = '/home/sites/php-dup-finder';

/** Concept 2 — two snippets that LOOK different but erode to one skeleton.
 *  Both literals single-quoted on purpose: the real PrettyPrinter preserves
 *  each String_'s source quote `kind`, and the owner's verify clause demands
 *  the two final lines be byte-identical. (Probed: kind=1 'x' / kind=2 "x".) */
$snippets = [
    'A' => "\$user = User::find('Bob')->name;",
    'B' => "\$post = Post::find('Hi')->title;",
];

$MODES = ['strict', 'default', 'aggressive'];

$parser = (new ParserFactory())->createForHostVersion();
$printer = new Standard();

/** @return list<Node> */
function harvest_one(\PhpParser\Parser $parser, string $src): array
{
    $stmts = $parser->parse("<?php\n" . $src);
    if ($stmts === null || count($stmts) !== 1) {
        throw new \RuntimeException("could not parse snippet: $src");
    }
    return $stmts;
}

/** @param list<Node> $stmts */
function canonical_line(\PhpParser\PrettyPrinter\Standard $printer, array $stmts, string $mode): string
{
    $block = new Block('harvest', new LineRange(1, 1), 'expression', null, null, null, $stmts[0]);
    (new Normalizer($mode))->normalize($block);
    return trim($printer->prettyPrint([$block->canonical]));
}

$data = ['snippets' => $snippets, 'modes' => []];

foreach ($snippets as $key => $src) {
    $stmts = harvest_one($parser, $src);
    $finder = new NodeFinder();
    $str = $finder->findFirst($stmts, static fn (Node $n): bool => $n instanceof Node\Scalar\String_);
    $kind = $str instanceof Node\Scalar\String_ ? $str->getAttribute('kind') : null;
    printf("%s  src (%2d, string kind=%s): %s\n", $key, strlen($src), var_export($kind, true), $src);
    foreach ($MODES as $mode) {
        $line = canonical_line($printer, $stmts, $mode);
        $data['modes'][$mode][$key] = $line;
        printf("   [%-10s] (%2d) %s\n", $mode, strlen($line), $line);
    }
    echo "\n";
}

$same = $data['modes']['aggressive']['A'] === $data['modes']['aggressive']['B'];
printf("aggressive lines identical: %s\n", $same ? 'YES (merge target valid)' : 'NO — abort');
if (!$same) {
    exit(1);
}

if (in_array('--write', $argv, true)) {
    $php = "<?php\n\n// GENERATED by harvest.php at build time — the REAL Normalizer output\n"
        . "// (mode => snippet => printed canonical line). Playback never loads the repo.\n"
        . "// Repo baseline: $REPO (re-run with --write after engine changes).\n\n"
        . "return " . var_export($data, true) . ";\n";
    file_put_contents(__DIR__ . '/normalized.php', $php);
    echo "wrote normalized.php (" . strlen($php) . " bytes)\n";
}
